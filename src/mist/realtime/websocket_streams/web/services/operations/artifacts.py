@dataclass(slots=True)
class BatchArtifactRecord:
    """Hold one bounded batch artifact tree and its download pins."""

    artifact_id: str  # The path component is generated by the portal.
    directory: Path  # The resolved tree stays under the configured data root.
    targets: tuple[BatchTargetRequest, ...]  # Frozen targets define stable output names.
    output: Mapping[str, object]  # The checked layout chooses combined or grouped output.
    target_indexes: dict[str, int]  # Hash-backed target keys map to stable numeric files.
    lock: threading.RLock = field(default_factory=threading.RLock)  # Serialize writes and pin changes.
    bytes_written: int = 0  # The limit counts every saved layout copy.
    sequence: int = 0  # One sequence orders all target results.
    files: set[str] = field(default_factory=set)  # The manifest lists only files written by this record.
    status: str = "writing"  # The public summary reports the artifact lifecycle.
    complete: bool = False  # ZIP download waits until every target has ended.
    partial: bool = False  # A failed target or writer marks the final output partial.
    pins: int = 0  # Active downloads block deletion until their response closes.
    outcomes: list[dict[str, object]] = field(default_factory=list)  # The manifest keeps one target result each.
    owner_pid: int = field(default_factory=os.getpid)  # Restart cleanup keeps artifacts owned by live workers.


class BatchArtifactWriter:
    """Bind one artifact record to the batch target sink callbacks."""

    def __init__(self, service: SessionArtifactService, record: BatchArtifactRecord) -> None:
        """Store the service and one private record."""
        self._storage, self._record = service._storage, record  # Callbacks never accept a browser path.

    @property
    def artifact_id(self) -> str:
        """Return the private artifact identifier for the plan."""
        return self._record.artifact_id  # Only the service uses this path token.

    def write_result(
        self, target_key: str, identity: Mapping[str, object], kind: str, content: object, summary: str | None
    ) -> None:
        """Persist one redacted result through the owning service."""
        payload = {"target": dict(identity), "kind": kind, "content": content, "summary": summary or None}
        self._storage.results.write(self._record, target_key, payload)  # Keep persistence under one owner.

    def finish(self, outcomes: list[dict[str, object]]) -> None:
        """Persist target outcomes and close the artifact manifest."""
        self._storage.finish(self._record, outcomes)  # Close only this writer's record.

    def discard(self) -> None:
        """Remove one artifact tree after an admission refusal."""
        self._storage.discard(self._record)  # Admission refusal removes the private tree.


class BatchArtifactStorage:
    """Own artifact persistence through bounded, cohesive storage components."""

    def __init__(self, owner: SessionArtifactService, reason: str | None, root: Path) -> None:
        """Share live limits and safe paths across all storage components."""
        self.owner, self.reason = owner, reason  # Read quotas from the service at each write.
        self.files = self.Files(root)  # Keep path validation in one component.
        self.metadata = self.Metadata(self)  # Keep redaction and manifest encoding together.
        self.results = self.Results(self)  # Serialize all result writes under the record lock.
        self.retention = self.Retention(self.files)  # Delete only verified, unowned trees.
        self.streams = self.Streams(self.files)  # Downloads share the same path checks.

    def prepare(self, targets: tuple[BatchTargetRequest, ...], output: Mapping[str, object]) -> BatchArtifactWriter:
        """Create one private output tree before public session admission."""
        self.require_ready()  # A not-ready portal cannot own output.
        root = self.files.safe_root()  # Resolve only the configured data child.
        self.retention.cleanup_orphans(root)  # Preserve trees owned by live local processes.
        artifact_id = secrets.token_hex(16)  # Generate a safe path component.
        directory = root / artifact_id  # Keep the tree directly below the data root.
        try:
            directory.mkdir(mode=0o700)  # Create a private session-owned directory.
        except OSError as error:
            logger.emit(logging.ERROR, "web.artifact.batch.create.error", {"status": type(error).__name__})
            raise StreamRequestError("output_failed", "The batch output directory could not be created.") from error
        indexes = {target.target_key: index for index, target in enumerate(targets)}  # Freeze target order.
        record = BatchArtifactRecord(artifact_id, directory, targets, dict(output), indexes)
        try:
            self.metadata.write(record)  # Reserve space for the final outcome manifest.
        except StreamRequestError:
            self.files.remove_tree(directory)  # Remove an unusable admission tree.
            raise
        return BatchArtifactWriter(self.owner, record)  # Bind the writer after manager admission.

    def finish(self, record: BatchArtifactRecord, outcomes: list[dict[str, object]]) -> None:
        """Save final target outcomes and close the output tree."""
        with record.lock:
            record.outcomes = [self.metadata.codec.outcome(item) for item in outcomes]  # Remove private metadata.
            record.partial = record.partial or any(item.get("state") != "completed" for item in outcomes)
            if record.status != "failed":
                record.status = "ready"  # The manifest write must succeed before completion.
            self.metadata.write(record)  # Persist state within the reserved metadata limit.
            record.complete = True  # Partial results also permit archive creation.
            if record.status == "failed":
                raise StreamRequestError("output_failed", "The batch output is incomplete.")

    def discard(self, record: BatchArtifactRecord) -> None:
        """Remove one tree when session admission fails."""
        with record.lock:
            if record.pins:
                raise StreamRequestError("output_failed", "The batch output is still in use.")
            self.files.verify_directory(record)  # Validate ownership before deletion.
            self.files.remove_tree(record.directory)  # Delete only the verified tree.

    def require_ready(self) -> None:
        """Raise when the WebSocket engine is not ready."""
        if self.reason is not None:  # Missing credentials or imports block artifact actions.
            raise StreamRequestError("not_ready", self.reason)  # Preserve the contract error.

    @dataclass
    class Files:
        """Validate artifact paths and remove only their verified trees."""

        root: Path  # All artifacts belong below this configured application directory.

        def safe_root(self) -> Path:
            """Create and validate the application data directory."""
            try:
                self.root.mkdir(parents=True, exist_ok=True, mode=0o700)  # Keep runtime output private.
                if self.root.is_symlink():
                    raise OSError("The artifact root is a symbolic link.")
                return self.root.resolve(strict=True)  # Compare all owners against a resolved root.
            except OSError as error:
                logger.emit(logging.ERROR, "web.artifact.root.error", {"status": type(error).__name__})
                raise StreamRequestError("output_failed", "The batch output directory is not available.") from error

        def safe_file(self, record: BatchArtifactRecord, relative: Path) -> Path:
            """Resolve one generated relative file beneath its private tree."""
            if relative.is_absolute() or ".." in relative.parts:
                raise StreamRequestError("output_failed", "The output path is not safe.")
            path = record.directory.joinpath(relative)  # Build only a checked relative path.
            base = record.directory.resolve()  # Resolve the private tree before containment checks.
            current = record.directory  # Check each intermediate folder for links.
            for part in relative.parts[:-1]:
                current = current / part  # Preserve each intermediate path component.
                if current.is_symlink():
                    raise StreamRequestError("output_failed", "The output path is not safe.")
            parent = path.parent.resolve()  # Missing group folders still need containment checks.
            if base not in parent.parents and parent != base:
                raise StreamRequestError("output_failed", "The output path is outside the batch tree.")
            if path.is_symlink():
                raise StreamRequestError("output_failed", "The output path is not safe.")
            return path  # Never expose an unchecked path to a writer or download.

        def verify_directory(self, record: BatchArtifactRecord) -> None:
            """Require one generated directory directly under the configured root."""
            root = self.safe_root()  # Recheck the configured boundary before deletion.
            if record.directory.is_symlink() or record.directory.name != record.artifact_id:
                raise StreamRequestError("cleanup_pending", "The batch output path is not safe.")
            if record.directory.resolve().parent != root:
                raise StreamRequestError("cleanup_pending", "The batch output path is outside its data root.")

        @staticmethod
        def remove_tree(directory: Path) -> None:
            """Remove one non-symlink path after its owner verifies the parent."""
            if directory.is_symlink():
                raise StreamRequestError("output_failed", "The batch output path is not safe.")
            try:
                shutil.rmtree(directory)  # Remove this exact verified tree, not its neighbors.
            except OSError as error:
                logger.emit(logging.ERROR, "web.artifact.batch.cleanup.error", {"status": type(error).__name__})
                raise StreamRequestError("cleanup_pending", "The batch output could not be removed.") from error

        class Layout:
            """Derive saved output names only from frozen target identities."""

            @classmethod
            def paths(cls, record: BatchArtifactRecord, target_key: str) -> tuple[Path, ...]:
                """Return combined and grouped paths for one target result."""
                paths: list[Path] = []  # Count every requested layout against the quota.
                mode = record.output.get("mode")  # The preview freezes the layout.
                if mode in {"combined", "both"}:
                    paths.append(Path("results") / "combined.jsonl")  # Keep the combined name stable.
                if mode in {"grouped", "both"}:
                    index = record.target_indexes.get(target_key)  # Use the frozen numeric target order.
                    if index is None:
                        raise StreamRequestError("output_failed", "The result target is not part of the preview.")
                    group = str(record.output.get("group_by", "site"))  # Select a validated grouping choice.
                    target = next(item for item in record.targets if item.target_key == target_key)
                    group_value = cls.group_value(target.identity, group)  # Do not use browser labels in paths.
                    group_key = hashlib.sha256(group_value.encode("utf-8")).hexdigest()[:16]
                    paths.append(Path("results") / group / group_key / f"target-{index:04d}.jsonl")
                return tuple(paths)  # Return only server-generated relative paths.

            @staticmethod
            def group_value(identity: Mapping[str, object], group: str) -> str:
                """Select one catalog identity value for a grouped folder."""
                fields = {
                    "site": ("site_id",),
                    "device_type": ("device_type",),
                    "device": ("site_id", "device_id", "target_id"),
                    "client": ("site_id", "client_mac"),
                }  # Keep grouping choices independent of browser labels.
                values = [str(identity.get(key) or "unassigned") for key in fields[group]]
                return ":".join(values)  # Preserve the established grouping hash input.

    @dataclass
    class Results:
        """Serialize bounded result records and account for every layout copy."""

        storage: BatchArtifactStorage  # Share the live quotas, redactor, and checked paths.

        def write(self, record: BatchArtifactRecord, target_key: str, payload: dict[str, object]) -> None:
            """Write one target result to the selected saved layouts."""
            with record.lock:
                if record.status != "writing":
                    raise StreamRequestError("output_failed", "The batch output is not writable.")
                record.sequence += 1  # Assign one order across all target workers.
                line = self.encode(record.sequence, payload)  # Redact before persistence.
                paths = self.storage.files.Layout.paths(record, target_key)  # Use frozen target identities.
                required_bytes = len(line) * len(paths)  # Count all requested layout copies.
                if (
                    len(line) > self.storage.owner.RECORD_LIMIT
                    or record.bytes_written + required_bytes > self.storage.owner.OUTPUT_LIMIT
                ):
                    record.status, record.partial = "failed", True  # Preserve an explicit quota failure.
                    raise StreamRequestError("output_failed", "The batch output limit was reached.")
                self.save(record, paths, line)  # Keep storage failures inside the writer boundary.

        def encode(self, sequence: int, payload: Mapping[str, object]) -> bytes:
            """Encode the established result envelope with boundary redaction."""
            envelope = {
                "seq": sequence,
                "target": self.storage.metadata.codec.redact(payload["target"]),
                "kind": payload["kind"],
                "content": self.storage.metadata.codec.redact(payload["content"]),
                "summary": self.storage.metadata.codec.redact(payload["summary"]) if payload["summary"] else None,
            }  # Preserve result field order and the existing JSON Lines shape.
            return (json.dumps(envelope, ensure_ascii=True, separators=(",", ":")) + "\n").encode("utf-8")

        def save(self, record: BatchArtifactRecord, paths: tuple[Path, ...], line: bytes) -> None:
            """Append each layout copy and count only completed writes."""
            try:
                for relative in paths:
                    path = self.storage.files.safe_file(record, relative)  # Reject links and traversal.
                    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)  # Keep group folders private.
                    self.append(path, line)  # Keep one complete JSON object per line.
                    record.files.add(relative.as_posix())  # List only completed writes in the manifest.
                    record.bytes_written += len(line)  # Count each saved copy against the hard cap.
            except OSError as error:
                record.status, record.partial = "failed", True  # Preserve the required file failure.
                logger.emit(logging.ERROR, "web.artifact.batch.write.error", {"status": type(error).__name__})
                raise StreamRequestError("output_failed", "The batch output could not be saved.") from error

        @staticmethod
        def append(path: Path, line: bytes) -> None:
            """Append one complete record without following a file link."""
            if path.is_symlink():
                raise OSError("The output path is a symbolic link.")
            with path.open("ab") as stream:
                stream.write(line)  # Append only after the final link check.

    class Metadata:
        """Own safe manifest encoding and atomic replacement."""

        def __init__(self, storage: BatchArtifactStorage) -> None:
            """Share the storage budget and one redactor across manifests."""
            self.storage = storage  # Read the live manifest limit at each replacement.
            self.codec = self.Codec(storage.owner)  # Redact results and outcomes at one boundary.

        def write(self, record: BatchArtifactRecord) -> None:
            """Replace the manifest atomically within its metadata budget."""
            encoded = self.encode(record)  # Check the complete metadata budget before touching a file.
            path = record.directory / "manifest.json"  # Keep the established manifest location.
            if path.is_symlink():
                record.status, record.partial = "failed", True  # Refuse linked metadata.
                raise StreamRequestError("output_failed", "The batch manifest path is not safe.")
            try:
                temporary = record.directory / ".manifest.tmp"  # Stage one complete manifest.
                with temporary.open("wb") as stream:
                    stream.write(encoded)  # Complete the bytes before atomic replacement.
                os.replace(temporary, path)  # Readers never see partial metadata.
            except OSError as error:
                record.status, record.partial = "failed", True  # Preserve a failed metadata write.
                logger.emit(logging.ERROR, "web.artifact.batch.manifest.error", {"status": type(error).__name__})
                raise StreamRequestError("output_failed", "The batch manifest could not be saved.") from error

        def encode(self, record: BatchArtifactRecord) -> bytes:
            """Encode only safe manifest fields and enforce the reserved quota."""
            payload = {
                "status": record.status,
                "partial": record.partial,
                "sequence": record.sequence,
                "owner_pid": record.owner_pid,
                "files": sorted(record.files),
                "targets": record.outcomes,
                "expires_at": self.codec.expiry(None, 600),
            }  # Keep the established on-disk expiry independent of service overrides.
            encoded = json.dumps(payload, ensure_ascii=True, separators=(",", ":")).encode("utf-8")
            if len(encoded) > self.storage.owner.MANIFEST_LIMIT:
                record.status, record.partial = "failed", True  # Refuse oversized target metadata.
                raise StreamRequestError("output_failed", "The batch manifest exceeds its size limit.")
            return encoded  # Persist only a complete, bounded payload.

        @dataclass
        class Codec:
            """Redact output values and format safe public metadata."""

            owner: SessionArtifactService  # Record quotas remain configurable on the service.
            redactor: SecretRedactor = field(default_factory=SecretRedactor)  # Share one boundary redactor.

            def redact(self, value: object) -> object:
                """Redact strings recursively before they enter an artifact."""
                if isinstance(value, str):
                    return self.redactor.redact(value, self.owner.RECORD_LIMIT)  # Bound every saved string.
                if isinstance(value, bytes):
                    return self.redactor.redact(value.decode("utf-8", errors="replace"), self.owner.RECORD_LIMIT)
                if isinstance(value, Mapping):
                    return {str(key): self.redact(item) for key, item in value.items()}  # Preserve field names.
                if isinstance(value, (list, tuple)):
                    return [self.redact(item) for item in value]  # Retain the JSON array shape.
                if value is None or isinstance(value, (bool, int, float)):
                    return value  # Keep JSON scalar types unchanged.
                return self.redactor.redact(str(value), self.owner.RECORD_LIMIT)  # Bound other printable values.

            def outcome(self, value: Mapping[str, object]) -> dict[str, object]:
                """Keep only public target identity and final progress fields."""
                allowed = {
                    "target",
                    "state",
                    "started_at",
                    "ended_at",
                    "reason_code",
                    "result_count",
                    "command_index",
                    "completion",
                }  # Never persist a private command or target key.
                return {key: self.redact(value[key]) for key in allowed if key in value}  # Redact allowed values.

            @staticmethod
            def expiry(session: Any, seconds: int) -> str:
                """Return the UTC expiry from a session end or the current time."""
                ended = getattr(session, "ended_at", None)  # Missing end times use the current time.
                if isinstance(ended, str) and ended:
                    try:
                        moment = datetime.fromisoformat(ended.replace("Z", "+00:00"))  # Accept UTC API text.
                    except ValueError:
                        moment = datetime.now(UTC)  # Preserve retention for malformed timestamps.
                else:
                    moment = datetime.now(UTC)  # Active sessions have no final end time.
                return (moment + timedelta(seconds=seconds)).replace(microsecond=0).isoformat().replace("+00:00", "Z")

    @dataclass
    class Retention:
        """Remove abandoned artifact trees without touching active workers."""

        files: BatchArtifactStorage.Files  # Deletion uses the shared safe filesystem boundary.

        def cleanup_orphans(self, root: Path) -> None:
            """Remove trees only when their recorded local process is absent."""
            try:
                directories = tuple(root.iterdir())  # Complete the scan before deleting a tree.
            except OSError as error:
                logger.emit(logging.ERROR, "web.artifact.cleanup.scan.error", {"status": type(error).__name__})
                raise StreamRequestError("output_failed", "The batch output directory cannot be scanned.") from error
            for directory in directories:
                owner_pid = self.owner_pid(directory)  # Unsafe or unreadable candidates have no known owner.
                if isinstance(owner_pid, int) and not self.process_is_alive(owner_pid):
                    self.files.remove_tree(directory)  # Remove only one verified orphan at a time.

        @staticmethod
        def owner_pid(directory: Path) -> object:
            """Read ownership only from a valid private tree and a regular manifest."""
            if directory.is_symlink() or not directory.is_dir() or not re.fullmatch(r"[0-9a-f]{32}", directory.name):
                return None  # Unrelated folders and links never become cleanup candidates.
            manifest = directory / "manifest.json"  # Ownership is recorded at admission.
            if manifest.is_symlink() or not manifest.is_file():
                return None  # Preserve incomplete or linked metadata.
            try:
                payload = json.loads(manifest.read_text(encoding="utf-8"))  # Read only the checked manifest.
                return payload.get("owner_pid") if isinstance(payload, dict) else None  # Require an object.
            except (OSError, json.JSONDecodeError):
                return None  # An unknown owner is not proof of an abandoned tree.

        @staticmethod
        def process_is_alive(process_id: int) -> bool:
            """Return whether a recorded local process still exists."""
            try:
                os.kill(process_id, 0)  # Check existence without signaling the process.
                return True  # Keep a tree owned by a live worker.
            except ProcessLookupError:
                return False  # Only proven process absence permits deletion.
            except PermissionError:
                return True  # Preserve trees when process access is denied.

    @dataclass
    class Streams:
        """Create pinned JSON Lines snapshots and completed ZIP archives."""

        files: BatchArtifactStorage.Files  # Every downloaded file needs the same path checks.

        def lines(self, record: BatchArtifactRecord) -> tuple[str, Iterator[str]]:
            """Pin one result snapshot and stream its saved JSON Lines."""
            with record.lock:
                record.pins += 1  # Cleanup must wait for the response iterator.
                last_sequence = record.sequence  # Later writes do not enter this snapshot.
                combined = record.directory / "results" / "combined.jsonl"  # Preserve combined layout selection.
                paths = [
                    self.files.safe_file(record, Path(item)) for item in sorted(record.files) if item.endswith(".jsonl")
                ]
            stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")  # Use a server-generated UTC name.
            return f"websocket-batch-{stamp}.jsonl", self.pinned_lines(record, paths, combined.exists(), last_sequence)

        def pinned_lines(
            self, record: BatchArtifactRecord, paths: list[Path], has_combined: bool, last_sequence: int
        ) -> Iterator[str]:
            """Stream a stable partial snapshot and release its pin."""
            try:
                lines = (
                    self.combined_lines(self.files.safe_file(record, Path("results") / "combined.jsonl"), last_sequence)
                    if has_combined
                    else self.grouped_lines(paths, last_sequence)
                )
                yield from lines  # Preserve lazy download behavior.
            finally:
                with record.lock:
                    record.pins -= 1  # Release the cleanup pin even when iteration fails.

        @staticmethod
        def combined_lines(path: Path, last_sequence: int) -> Iterator[str]:
            """Yield combined records no newer than the download snapshot."""
            with path.open("r", encoding="utf-8") as stream:
                for line in stream:
                    if int(json.loads(line).get("seq", 0)) <= last_sequence:
                        yield line  # Keep complete persisted JSON Lines unchanged.

        @staticmethod
        def grouped_lines(paths: list[Path], last_sequence: int) -> Iterator[str]:
            """Merge grouped target files by their saved global sequence."""
            records = [
                json.loads(line)
                for path in paths
                for line in path.read_text(encoding="utf-8").splitlines()
                if int(json.loads(line).get("seq", 0)) <= last_sequence
            ]  # Exclude records written after the response snapshot.
            for record in sorted(records, key=lambda item: item["seq"]):
                yield json.dumps(record, ensure_ascii=True, separators=(",", ":")) + "\n"  # Keep global order.

        def archive(self, record: BatchArtifactRecord) -> tuple[str, bytes]:
            """Build a ZIP from verified saved paths and the final manifest."""
            output = BytesIO()  # The storage quota bounds the archive snapshot.
            with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
                for relative in sorted(record.files):
                    path = self.files.safe_file(record, Path(relative))  # Recheck links before reading.
                    archive.write(path, relative)  # Store no host path in the archive.
                archive.write(self.files.safe_file(record, Path("manifest.json")), "manifest.json")
            stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")  # Use a server-generated UTC name.
            return f"websocket-batch-{stamp}.zip", output.getvalue()  # Return a completed in-memory snapshot.


class BatchSessionBindings:
    """Own public session bindings, manifest summaries, and retention cleanup."""

    def __init__(self, manager: Any, storage: BatchArtifactStorage) -> None:
        """Share the manager and protect public bindings with one lock."""
        self.manager, self.storage = manager, storage  # Session existence remains the manager's decision.
        self.batches: dict[str, BatchArtifactWriter] = {}  # Public ids never become directory names.
        self.lock = threading.RLock()  # Bindings and cleanup use the same lock.

    def bind_batch(self, session_id: str, writer: BatchArtifactWriter) -> None:
        """Bind one admitted public parent to its private artifact tree."""
        with self.lock:
            self.batches[session_id] = writer  # Bind only after successful manager admission.

    def writer(self, session_id: str) -> BatchArtifactWriter | None:
        """Return the writer bound to one public session id."""
        with self.lock:
            return self.batches.get(session_id)  # Single Site sessions have no artifact tree.

    def manifest(self, session_id: str) -> dict[str, object]:
        """Return one safe manifest for an existing batch parent."""
        session = self.manager.session(session_id)  # Expired sessions cannot fetch stale artifacts.
        writer = self.writer(session_id)  # Single Site sessions have no batch manifest.
        if writer is None:
            raise StreamRequestError("not_batch", "The session is not a Multi Site batch.")
        record = writer._record  # The private record owns manifest state.
        with record.lock:
            return {
                "status": record.status,
                "expires_at": self.storage.metadata.codec.expiry(session, self.storage.owner.RETENTION_SECONDS),
                "partial": record.partial or not record.complete,
                "files": sorted(record.files),
                "targets": [dict(item) for item in record.outcomes],
            }  # Return no private directory or raw command.

    def cleanup_expired(self, session_id: str) -> bool:
        """Remove one ended session tree during the manager retention pass."""
        writer = self.writer(session_id)  # Single Site sessions have no tree to remove.
        if writer is None:
            return True  # Preserve the manager's Single Site retention path.
        record = writer._record  # Pins belong to this exact private tree.
        with record.lock:
            if record.pins:
                return False  # Retry cleanup after the response closes.
            try:
                self.storage.files.verify_directory(record)  # Verify ownership before deletion.
                self.storage.files.remove_tree(record.directory)  # Remove only this tree.
            except StreamRequestError:
                return False  # Preserve retry behavior when removal fails.
        with self.lock:
            self.batches.pop(session_id, None)  # Remove only the successfully deleted binding.
        return True  # The manager may now expire the parent.


class SessionArtifactService:
    """Compose batch storage and public bindings with session download actions."""

    OUTPUT_LIMIT = 63 * 1024 * 1024  # Reserve one MiB of the 64 MiB cap for metadata.
    MANIFEST_LIMIT = 1024 * 1024  # Keep target metadata within the reserved quota.
    RECORD_LIMIT = 1024 * 1024  # Reject one oversized result before writing it.
    RETENTION_SECONDS = 600  # Match the existing ended-session retention window.

    def __init__(self, manager: Any, reason: str | None, root: Path | None = None) -> None:
        """Compose storage and binding operations without forwarding wrappers."""
        self._manager = manager  # The ready manager owns retained session data.
        self._storage = BatchArtifactStorage(self, reason, root or Path("data/websocket-streams"))
        self._bindings = BatchSessionBindings(manager, self._storage)  # Share one public session registry.
        self.prepare_batch = self._storage.prepare  # Expose admission through its owning component.
        self.bind_batch = self._bindings.bind_batch  # Expose the atomic public binding operation.
        self.manifest = self._bindings.manifest  # Expose the safe public summary operation.
        self.cleanup_expired = self._bindings.cleanup_expired  # The manager calls the retention owner directly.

    def delete(self, session_id: str) -> dict[str, object]:
        """Delete one ended session."""
        self._storage.require_ready()  # A not-ready portal has no retained session.
        logger.emit(logging.INFO, "web.artifact.delete.start")  # Record the bounded delete action.
        writer = self._bindings.writer(session_id)  # Single Site sessions have no file tree.
        if writer is not None:
            session = self._manager.session(session_id)  # The manager owns live state.
            if session.live:
                raise StreamRequestError("session_live", "Stop the session before you delete it.")
            with writer._record.lock:
                if writer._record.pins:
                    raise StreamRequestError("cleanup_pending", "A batch download is still active.")
                self._storage.discard(writer._record)  # Remove only the verified session-owned tree.
            with self._bindings.lock:
                self._bindings.batches.pop(session_id, None)  # Remove the successfully deleted binding.
        self._manager.delete(session_id)  # Let the manager refuse live or unknown sessions.
        logger.emit(logging.DEBUG, "web.artifact.delete.finish", {"status": "deleted"})  # Confirm deletion.
        return {"ok": True}  # Preserve the route confirmation.

    def download(self, session_id: str) -> tuple[str, Iterator[str]]:
        """Return one session file name and JSON Lines iterator."""
        self._storage.require_ready()  # A not-ready portal has no retained session.
        logger.emit(logging.INFO, "web.artifact.download.start")  # Record stream preparation.
        writer = self._bindings.writer(session_id)  # Batch output lives outside the message buffer.
        if writer is not None:
            self._manager.session(session_id)  # Refuse expired batch ids before reading their tree.
            filename, lines = self._storage.streams.lines(writer._record)  # Snapshot persisted batch output.
        else:
            filename, lines = self._manager.download(session_id)  # Preserve Single Site downloads.
        logger.emit(logging.DEBUG, "web.artifact.download.finish", {"status": "ready"})  # Log no filename.
        return filename, lines  # Preserve lazy download behavior.

    def zip_download(self, session_id: str) -> tuple[str, bytes]:
        """Return one completed saved layout as a bounded ZIP archive."""
        self._storage.require_ready()  # A not-ready portal cannot create downloads.
        self._manager.session(session_id)  # Reject unknown or expired parents before file access.
        writer = self._bindings.writer(session_id)  # Single Site sessions have no ZIP layout.
        if writer is None:
            raise StreamRequestError("not_batch", "The session is not a Multi Site batch.")
        record = writer._record  # The private record owns completion state and pins.
        with record.lock:
            if not record.complete:
                raise StreamRequestError("artifact_not_ready", "The batch archive is not ready.")
            record.pins += 1  # Pin files while the archive snapshot is built.
        try:
            return self._storage.streams.archive(record)  # Build outside the manager lock.
        finally:
            with record.lock:
                record.pins -= 1  # Release the cleanup pin after the snapshot is complete.
